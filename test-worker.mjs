import worker from './index.js';
import assert from 'node:assert/strict';
const ORIGIN='https://b88677220-rgb.github.io';
const store=new Map();
const kv={async get(k){return store.get(k)??null;},async put(k,v){store.set(k,String(v));}};
const env={ALLOWED_ORIGIN:ORIGIN,OPENAI_API_KEY:'test-key',OPENAI_MODEL:'gpt-6-luna',RATE_LIMIT_KV:kv};
const makeReq=(body,ip='203.0.113.7',origin=ORIGIN)=>new Request('https://worker.example/api/ai',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json','CF-Connecting-IP':ip},body:typeof body==='string'?body:JSON.stringify(body)});
const mockOutput=(obj,usage={input_tokens:123,output_tokens:45})=>new Response(JSON.stringify({output:[{content:[{type:'output_text',text:JSON.stringify(obj)}]}],usage}),{status:200,headers:{'Content-Type':'application/json'}});
let r=await worker.fetch(new Request('https://worker.example/api/ai',{method:'OPTIONS',headers:{Origin:ORIGIN}}),env);
assert.equal(r.status,204,'allowed preflight');
r=await worker.fetch(makeReq({action:'health'},'203.0.113.1','https://evil.example'),env);
assert.equal(r.status,403,'reject foreign origin');
r=await worker.fetch(makeReq({action:'health'}),{...env,RATE_LIMIT_KV:null});
assert.equal(r.status,429,'fail closed without KV');
const brokenKV={async get(){throw new Error('KV unavailable')},async put(){}};
r=await worker.fetch(makeReq({action:'health'},'203.0.113.2'),{...env,RATE_LIMIT_KV:brokenKV});
assert.equal(r.status,429,'fail closed on KV error');
r=await worker.fetch(makeReq({action:'health'},'203.0.113.3'),env);
assert.equal(r.status,200);
assert.deepEqual((await r.json()).result,{status:'ok'});
r=await worker.fetch(makeReq({action:'unknown'},'203.0.113.4'),env);
assert.equal(r.status,400,'reject unknown action');
r=await worker.fetch(makeReq('{not-json','203.0.113.5'),env);
assert.equal(r.status,400,'reject malformed JSON');
r=await worker.fetch(makeReq('x'.repeat(10001),'203.0.113.6'),env);
assert.equal(r.status,413,'reject oversized body');
let captured=null;
globalThis.fetch=async (_url,options)=>{captured=JSON.parse(options.body);return mockOutput({needs_clarification:false,question:'',kcal:650,protein_g:35,confidence:'medium',notes:'Schätzung'});};
r=await worker.fetch(makeReq({action:'meal',payload:{meal:'Pasta mit Hähnchen'}},'203.0.113.7'),env);
assert.equal(r.status,200,'valid meal response');
let data=await r.json();
assert.equal(data.result.kcal,650);
assert.deepEqual(data.usage,{input_tokens:123,output_tokens:45});
assert.equal(captured.model,'gpt-6-luna');
assert.equal(captured.max_output_tokens,300);
assert.equal(captured.store,false);
store.clear();
globalThis.fetch=async ()=>mockOutput({kcal:999999,protein_g:2,needs_clarification:false});
r=await worker.fetch(makeReq({action:'meal',payload:{meal:'Test'}},'203.0.113.8'),env);
assert.equal(r.status,502,'invalid model output rejected');
store.clear();
let calls=0;
globalThis.fetch=async ()=>{calls++;return mockOutput({answer:'Trainiere progressiv und erhole dich ausreichend.'});};
for(let i=0;i<5;i++){r=await worker.fetch(makeReq({action:'coach',payload:{message:'Tipps'}},'203.0.113.9'),env);assert.equal(r.status,200,`minute request ${i+1} allowed`);}
r=await worker.fetch(makeReq({action:'coach',payload:{message:'Noch ein Tipp'}},'203.0.113.9'),env);
assert.equal(r.status,429,'sixth request blocked');
assert.equal(calls,5,'provider not called after rate limit');
store.clear();
r=await worker.fetch(makeReq({action:'meal',payload:{meal:'x'.repeat(3100)}},'203.0.113.10'),env);
assert.equal(r.status,413,'action payload limit enforced');
console.log('Worker QA passed: CORS, KV fail-closed, health, malformed/oversized input, model privacy, token caps, usage, output validation, per-IP rate limits.');
